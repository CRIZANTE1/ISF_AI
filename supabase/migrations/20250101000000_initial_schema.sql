-- 1. Create ENUM types for controlled vocabularies
CREATE TYPE public.equipment_type AS ENUM (
    'extintor',
    'mangueira',
    'abrigo',
    'scba',
    'chuveiro_lavaolhos',
    'camara_espuma',
    'multigas',
    'alarme',
    'canhao_monitor'
);

CREATE TYPE public.equipment_status AS ENUM (
    'ok',
    'vencido',
    'pendente',
    'nao_conforme',
    'baixado'
);


-- 2. Create Profiles table to store user data
CREATE TABLE public.profiles (
  id UUID NOT NULL PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name TEXT,
  avatar_url TEXT,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Set up Row Level Security (RLS)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public profiles are viewable by everyone."
  ON public.profiles FOR SELECT
  USING ( true );

CREATE POLICY "Users can insert their own profile."
  ON public.profiles FOR INSERT
  WITH CHECK ( auth.uid() = id );

CREATE POLICY "Users can update own profile."
  ON public.profiles FOR UPDATE
  USING ( auth.uid() = id );

-- This trigger automatically creates a profile entry when a new user signs up
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, full_name, avatar_url)
  VALUES (new.id, new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'avatar_url');
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();


-- 3. Create Equipment table for inventory
CREATE TABLE public.equipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    equipment_id TEXT NOT NULL UNIQUE, -- e.g., EXT-001
    equipment_type public.equipment_type NOT NULL,
    status public.equipment_status NOT NULL DEFAULT 'ok',
    specifications JSONB, -- For flexible data like brand, model, etc.
    localizacao TEXT,
    proxima_inspecao DATE,
    data_validade DATE,
    qr_code TEXT,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL
);

-- Set up Row Level Security (RLS)
ALTER TABLE public.equipment ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Authenticated users can manage equipment."
  ON public.equipment FOR ALL
  USING ( auth.role() = 'authenticated'::text )
  WITH CHECK ( auth.role() = 'authenticated'::text );

